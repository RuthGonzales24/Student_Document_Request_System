        private void displaySavedRequests() {
        try {
            List<RequestStore.Request> filtered =
                    new ArrayList<>();

            javax.swing.table.DefaultTableModel model =
                    RequestStore.newTableModel();

            for (RequestStore.Request request : RequestStore.load()) {
                if (studentId.equals(request.studentId)) {
                    filtered.add(request);
                    model.addRow(request.toRow());
                }
            }

            tblRequests.clearSelection();

            visibleRequests.clear();
            visibleRequests.addAll(filtered);

            tblRequests.setModel(model);

        } catch (IOException e) {
            showError(e);
        }
    }

        private RequestStore.Request selectedRequest() {
        int row = tblRequests.getSelectedRow();

        if (row == -1) {
            return null;
        }

        return visibleRequests.get(
                tblRequests.convertRowIndexToModel(row));
    }

        private void fillSelectedRequest() {
        RequestStore.Request request = selectedRequest();

        if (request != null) {
            cmbDocType.setSelectedItem(request.document);
            cmbPurpose.setSelectedItem(request.purpose);
        }
    }

        private void updateSelectedRequest() {
        RequestStore.Request request = selectedRequest();

        if (request == null) {
            JOptionPane.showMessageDialog(
                    this, "Select a request first.");
            return;
        }

        try {
            RequestStore.updateStudentRequest(
                    request,
                    studentId,
                    (String) cmbDocType.getSelectedItem(),
                    (String) cmbPurpose.getSelectedItem());

            displaySavedRequests();
            clearForm();

            JOptionPane.showMessageDialog(
                    this, "Request updated successfully.");

        } catch (IOException e) {
            showError(e);
        }
    }

        private void clearForm() {
        tblRequests.clearSelection();

        Name.setText(studentName);
        txtID.setText(studentId);

        cmbDocType.setSelectedIndex(0);
        cmbPurpose.setSelectedIndex(0);
    }

        private void showError(IOException e) {
        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Request Error",
                JOptionPane.ERROR_MESSAGE);
    }
