    private void btnAdminDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdminDeleteActionPerformed
        // TODO add your handling code here:                                              
    RequestStore.Request request = selectedRequest();

    if (request == null) {
        return;
    }

    int answer = JOptionPane.showConfirmDialog(
            this,
            "Delete the selected request?",
            "Confirm Deletion",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE);

    if (answer == JOptionPane.YES_OPTION) {
        try {
            RequestStore.delete(request);
            loadAllRequests();

            JOptionPane.showMessageDialog(
                    this, "Request deleted successfully.");

        } catch (IOException e) {
            showError(e);
        }
    }
    }//GEN-LAST:event_btnAdminDeleteActionPerformed

