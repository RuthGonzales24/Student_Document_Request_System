        private void loadAllRequests() {
        try {
            List<RequestStore.Request> loaded =
                    RequestStore.load();

            javax.swing.table.DefaultTableModel model =
                    RequestStore.newTableModel();

            for (RequestStore.Request request : loaded) {
                model.addRow(request.toRow());
            }

            tblAdminRequests.clearSelection();

            displayedRequests.clear();
            displayedRequests.addAll(loaded);

            tblAdminRequests.setModel(model);

        } catch (IOException e) {
            showError(e);
        }
    }

        private RequestStore.Request selectedRequest() {
        int row = tblAdminRequests.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(
                    this, "Select a request first.");
            return null;
        }

        return displayedRequests.get(
                tblAdminRequests.convertRowIndexToModel(row));
    }

        private void updateRequestStatus(String status) {
        RequestStore.Request request = selectedRequest();

        if (request == null) {
            return;
        }

        try {
            RequestStore.changeStatus(request, status);
            loadAllRequests();

            JOptionPane.showMessageDialog(
                    this, "Request marked as " + status + ".");

        } catch (IOException e) {
            showError(e);
        }
    }

        private void showError(IOException e) {
        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Admin Error",
                JOptionPane.ERROR_MESSAGE);
    }

