   static Account authenticate(String username, char[] password) {
    if (username.equals("admin")
            && Arrays.equals(
                    password, "admin123".toCharArray())) {

        return new Account(true, null, null);
    }

    if (username.equals("2103775")
            && Arrays.equals(
                    password, "student123".toCharArray())) {

        return new Account(
                false, "2103775", "Student One");
    }

    if (username.equals("2103665")
            && Arrays.equals(
                    password, "student123".toCharArray())) {

        return new Account(
                false, "2103665", "Student Two");
    }

    return null;
}

    static final class Account {
        final boolean admin;
        final String studentId;
        final String studentName;

        Account(
                boolean admin,
                String studentId,
                String studentName) {

            this.admin = admin;
            this.studentId = studentId;
            this.studentName = studentName;
        }
    }
